"""08 - Freeze every published number into one markdown file.

A methodology change that touches the panel changes every result downstream of
it, and the only honest way to report such a change is a before/after table.
That table is unsound if the two halves are assembled by hand, or by two
different pieces of code, or from a database that has since been retrained over.

So this script writes the snapshot, and it is the SAME script that will write
the one after the change. Identical queries, identical rounding, identical
ordering - the diff between two of its outputs is a real comparison rather than
a transcription.

It reads and writes nothing else: no model is loaded, no prediction is made, no
row is inserted. Running it twice against an unchanged database produces two
identical files.

    python scripts/08_snapshot_results.py --label before_event_lag_fix
    python scripts/08_snapshot_results.py --label after_event_lag_fix

Then simply diff the two files.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

import _bootstrap  # noqa: F401  - must precede pledgecast/config imports
from config import get_settings
from pledgecast.db import repository as repo
from pledgecast.db.connection import get_connection
from pledgecast.evaluation import power
from pledgecast.logging_config import get_logger, setup_logging

logger = get_logger(__name__)

OUT_DIR = Path("reports")


def _git(*args: str) -> str:
    """A git fact, or a placeholder. A snapshot must not fail outside a repo."""
    try:
        return subprocess.run(
            ["git", *args], capture_output=True, text=True, check=True
        ).stdout.strip()
    except Exception:  # noqa: BLE001 - provenance is nice to have, not load-bearing
        return "unavailable"


def _table(frame: pd.DataFrame, floatfmt: str = "{:.4f}") -> str:
    """A DataFrame as a markdown table, without adding a dependency for it."""
    if frame.empty:
        return "_(none)_\n"
    header = list(frame.columns)
    lines = ["| " + " | ".join(str(h) for h in header) + " |",
             "|" + "|".join("---" for _ in header) + "|"]
    for row in frame.itertuples(index=False):
        cells = []
        for value in row:
            if isinstance(value, float):
                cells.append("n/a" if pd.isna(value) else floatfmt.format(value))
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def build(settings) -> str:
    """Every published number, in one string."""
    with get_connection(settings=settings) as conn:
        runs = repo.load_model_runs(conn)
        metrics = repo.load_metrics(conn)
        panel = repo.load_panel(conn, valid_only=True)
        full_panel = repo.load_panel(conn, valid_only=False)
        backtest = repo.load_backtest_results(conn)
        active = repo.get_active_run(conn)
        counts = repo.table_counts(conn)
        stamp = repo.latest_training_session(conn)

        session = runs[runs["run_id"].map(repo.session_of) == stamp] if stamp else runs
        labels = panel[["symbol", "observation_date", "label"]]
        oof: dict[tuple[str, str], pd.DataFrame] = {}
        for row in session.itertuples(index=False):
            frame = repo.load_predictions(conn, run_id=row.run_id, source="backtest")
            if not frame.empty:
                oof[(row.model_name, row.experiment)] = frame.merge(
                    labels, on=["symbol", "observation_date"], how="inner"
                )

    parts: list[str] = []
    add = parts.append

    add("# Results snapshot\n")
    add(
        "Generated by `scripts/08_snapshot_results.py`. Every number below is read "
        "from the database, never transcribed.\n"
    )

    # ---------------------------------------------------------- provenance
    add("\n## Provenance\n")
    add(
        _table(
            pd.DataFrame(
                [
                    {"field": "commit", "value": _git("rev-parse", "HEAD")},
                    {"field": "commit subject", "value": _git("log", "-1", "--format=%s")},
                    {"field": "working tree", "value": _git("status", "--porcelain") or "clean"},
                    {"field": "training session", "value": stamp or "none"},
                    {"field": "active run", "value": (active or {}).get("run_id", "none")},
                ]
            )
        )
    )

    # ------------------------------------------------- the settings that matter
    add("\n## Configuration under test\n")
    add(
        "The parameters a methodology change would move. Anything else being equal "
        "is what makes a before/after comparison meaningful.\n\n"
    )
    features = settings.features
    label = settings.label
    # Values as strings: a mixed int/float column gets upcast by pandas, and an
    # integer parameter rendered as "11.0000" reads like a tolerance rather than
    # a count. These are configuration values and should appear verbatim.
    add(
        _table(
            pd.DataFrame(
                [
                    {"parameter": key, "value": str(value)}
                    for key, value in [
                        ("label.horizon_trading_days", label.horizon_trading_days),
                        ("label.drawdown_threshold", label.drawdown_threshold),
                        ("features.event_disclosure_lag_days",
                         features.event_disclosure_lag_days),
                        ("features.min_event_pct_equity", features.min_event_pct_equity),
                        ("features.event_window_days",
                         getattr(features, "event_window_days", "n/a")),
                        ("features.event_invocation_window_days",
                         getattr(features, "event_invocation_window_days", "n/a")),
                        ("power.n_bootstrap", settings.power.n_bootstrap),
                        ("power.confidence_level", settings.power.confidence_level),
                        ("power.bootstrap_seed", settings.power.bootstrap_seed),
                    ]
                ]
            )
        )
    )

    # ------------------------------------------------------------- data scale
    add("\n## Data scale\n")
    add(_table(pd.DataFrame(sorted(counts.items()), columns=["table", "rows"])))

    # ------------------------------------------------------- event coverage
    add("\n## Event feature coverage\n")
    add(
        "The share of panel rows any event feature can speak to. A stricter "
        "disclosure boundary lowers this, and the oracle ceiling is what says "
        "whether the remaining coverage could still have carried a finding.\n\n"
    )
    event_columns = [c for c in full_panel.columns if c.startswith("event_")]
    if event_columns:
        # rows_with_any_feature returns a boolean MASK, not a count - "present and
        # non-zero", which is the generous reading the oracle ceiling wants.
        covered = int(power.rows_with_any_feature(full_panel, event_columns).sum())
        add(
            _table(
                pd.DataFrame(
                    [
                        {"metric": "panel rows", "value": float(len(full_panel))},
                        {"metric": "rows with any event feature", "value": float(covered)},
                        {"metric": "coverage", "value": covered / max(len(full_panel), 1)},
                    ]
                ),
                floatfmt="{:.4f}",
            )
        )
    else:
        add("_(no event features in the panel)_\n")

    # ------------------------------------------------------- headline metric
    add("\n## Within-quarter AUC by experiment and model\n")
    aggregate = metrics[metrics["fold"] == -1].merge(
        session[["run_id", "model_name", "experiment"]], on="run_id"
    )
    primary = aggregate[aggregate["metric_name"] == settings.evaluation.primary_metric]
    wide = primary.pivot_table(
        index="experiment", columns="model_name", values="metric_value", aggfunc="last"
    ).reset_index()
    add(_table(wide))

    add("\n## Brier skill score by experiment and model\n")
    add(
        "Above zero beats predicting the base rate. These are the numbers behind "
        "calling the output a risk score rather than a calibrated probability.\n\n"
    )
    brier = aggregate[aggregate["metric_name"] == "brier_skill_score"]
    if not brier.empty:
        add(
            _table(
                brier.pivot_table(
                    index="experiment", columns="model_name", values="metric_value", aggfunc="last"
                ).reset_index()
            )
        )

    # ------------------------------------------------------- detectability
    add("\n## Detectability - every comparison with its interval\n")
    add(
        "The headline artefact. Each row is a treatment against its own baseline, "
        "paired by observation date, with a bootstrap-t interval over dates.\n\n"
    )
    rows = []
    for (model_name, experiment), treatment in sorted(oof.items()):
        if experiment not in settings.experiments:
            continue
        baseline = settings.experiment_baseline(experiment)
        control = oof.get((model_name, baseline))
        if baseline == experiment or control is None:
            continue
        result = power.paired_delta_ci(
            treatment,
            control,
            n_bootstrap=settings.power.n_bootstrap,
            confidence_level=settings.power.confidence_level,
            seed=settings.power.bootstrap_seed,
            min_rows=settings.evaluation.min_rows_per_quarter_for_auc,
        )
        rows.append(
            {
                "experiment": experiment,
                "vs": baseline,
                "model": model_name,
                "delta": result.get("delta"),
                "ci_low": result.get("ci_low"),
                "ci_high": result.get("ci_high"),
                "half_width": result.get("half_width"),
                "dates": result.get("n_dates"),
                "verdict": result.get("verdict"),
            }
        )
    detect = pd.DataFrame(rows)
    if not detect.empty:
        detect = detect.sort_values(["experiment", "model"]).reset_index(drop=True)
        add(_table(detect))
        add("\n### Verdict counts\n\n")
        add(
            _table(
                detect["verdict"].value_counts().rename_axis("verdict")
                .reset_index(name="count")
            )
        )

    # --------------------------------------------------------- economic backtest
    add("\n## Quintile backtest\n")
    if not backtest.empty:
        joined = backtest.merge(session[["run_id", "model_name", "experiment"]], on="run_id")
        pooled = (
            joined.groupby(["experiment", "quintile"])
            .agg(n_companies=("n_companies", "sum"), n_events=("n_events", "sum"))
            .reset_index()
        )
        pooled["event_rate"] = pooled["n_events"] / pooled["n_companies"]
        summary = []
        for experiment, block in pooled.groupby("experiment"):
            rates = block.set_index("quintile")["event_rate"]
            top = rates.get(settings.evaluation.n_quintiles)
            bottom = rates.get(1)
            summary.append(
                {
                    "experiment": experiment,
                    "Q1": bottom,
                    "Q5": top,
                    "Q5-Q1": None if top is None or bottom is None else top - bottom,
                    "Q5/Q1": None if not bottom else top / bottom,
                }
            )
        add(_table(pd.DataFrame(summary)))
        add(f"\nBase rate across labelled rows: **{panel['label'].mean():.4f}**\n")

    return "\n".join(parts)


def key_numbers(settings) -> dict:
    """The small, machine-readable core of the snapshot.

    ``tests/test_no_scientific_drift.py`` compares this against a freshly
    computed version, so a change that was supposed to be documentation-only
    cannot quietly move a published result. The markdown above is for reading;
    this is for asserting.
    """
    with get_connection(settings=settings) as conn:
        runs = repo.load_model_runs(conn)
        metrics = repo.load_metrics(conn)
        panel = repo.load_panel(conn, valid_only=True)
        active = repo.get_active_run(conn)
        stamp = repo.latest_training_session(conn)
        session = runs[runs["run_id"].map(repo.session_of) == stamp] if stamp else runs
        aggregate = metrics[metrics["fold"] == -1].merge(
            session[["run_id", "model_name", "experiment"]], on="run_id"
        )
        primary = aggregate[aggregate["metric_name"] == settings.evaluation.primary_metric]

    return {
        "active_run_id": (active or {}).get("run_id"),
        "training_session": stamp,
        "n_labelled_rows": int(len(panel)),
        "n_observation_dates": int(panel["observation_date"].nunique()),
        "base_rate": round(float(panel["label"].mean()), 6),
        # The scientific configuration. Phase 1 was defined as touching none of it.
        "config": {
            "horizon_trading_days": settings.label.horizon_trading_days,
            "drawdown_threshold": settings.label.drawdown_threshold,
            "event_disclosure_lag_days": settings.features.event_disclosure_lag_days,
            "min_event_pct_equity": settings.features.min_event_pct_equity,
            "n_bootstrap": settings.power.n_bootstrap,
            "confidence_level": settings.power.confidence_level,
            "bootstrap_seed": settings.power.bootstrap_seed,
        },
        "experiments": {
            name: sorted(experiment.features) for name, experiment in settings.experiments.items()
        },
        "primary_metric": {
            f"{row.experiment}|{row.model_name}": round(float(row.metric_value), 6)
            for row in primary.itertuples(index=False)
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--label",
        required=True,
        help="Names the files: reports/snapshot_<label>.md and .json",
    )
    args = parser.parse_args()

    setup_logging()
    settings = get_settings()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    path = OUT_DIR / f"snapshot_{args.label}.md"
    path.write_text(build(settings), encoding="utf-8")

    data = OUT_DIR / f"snapshot_{args.label}.json"
    data.write_text(json.dumps(key_numbers(settings), indent=2, sort_keys=True), encoding="utf-8")

    logger.info("wrote %s and %s", path, data)
    print(f"\n  wrote {path}\n  wrote {data}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
